int dm1_v1_fmtowns_wall_ornament_resolve(int global_index, int view_index,
                                        int japanese,
                                        DM1_V1_FmtownsWallOrnament *out)
{
    static const uint8_t bitmap_offset[13] = {
        0, 0, 1, 1, 1, 0, 0, 1, 1, 1, 0, 1, 1
    };
    if (out) memset(out, 0, sizeof(*out));
    if (!out || global_index < 0 || global_index >= 60 ||
        view_index < 0 || view_index >= 13 ||
        (japanese != 0 && japanese != 1)) return 0;
    out->global_index = global_index;
    out->view_index = view_index;
    out->coordinate_set = s_coordinate_set[global_index];
    out->zone_index = 1004 + out->coordinate_set * 13 + view_index;
    out->graphic_index = 121 + global_index * 2 + bitmap_offset[view_index];
    out->scale = view_index <= 4 ? 16 : 20;
    out->flip_horizontal = view_index == 1 || view_index == 6 || view_index == 11;
    out->palette_depth = view_index <= 4 ? 3 : 2;
    out->layout = s_layout[japanese][out->zone_index - 1004];
    return 1;
}
