int dm1_v1_fmtowns_region_lookup_pc34(
    uint16_t region_id, DM1_V1_FmtownsRegionRecord *out) {
    unsigned int i;
    if (!out) return 0;
    /* Walk the 23-block chain the same way the runtime does at
     * EDM.EXP 0x18db4: skip any block whose id_min..id_max range
     * does not contain the requested id, then return the record
     * at slot (id - id_min). */
    for (i = 0; i < DM1_V1_FMTOWNS_REGION_BLOCK_COUNT; ++i) {
        const DM1_V1_FmtownsRegionBlock *blk = &dm1_v1_fmtowns_region_blocks[i];
        if (region_id < blk->id_min || region_id > blk->id_max) continue;
        *out = dm1_v1_fmtowns_region_records[blk->record_base +
                                              (region_id - blk->id_min)];
        return 1;
    }
    return 0;
}

