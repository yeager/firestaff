void dm2_v1_convert_driver_palette(const uint8_t *src, int8_t *dst)
{
    for (int i = 0; i < DM2_V1_PAL_ENTRIES; i++) {
        src++; /* skip alpha byte */
        *dst++ = (int8_t)(*src++ >> 2);
        *dst++ = (int8_t)(*src++ >> 2);
        *dst++ = (int8_t)(*src++ >> 2);
    }
}

void dm2_v1_expand_palette_6to8(const int8_t *pal6, uint8_t *pal8)
{
    for (int i = 0; i < DM2_V1_PAL_SIZE; i++) {
        uint8_t v6 = (uint8_t)pal6[i];
        pal8[i] = (uint8_t)((v6 * 255 + 31) / 63);
    }
}
