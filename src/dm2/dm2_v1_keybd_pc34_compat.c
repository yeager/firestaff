/* ── Queue operations ────────────────────────────────────────────────── */

void dm2_v1_keybd_init(DM2_V1_Keybd *kbd)
{
    kbd->queueidx_in = 0;
    kbd->queueidx_out = 0;
    kbd->queuecnt = 0;
    memset(kbd->kbdqueue, 0, sizeof(kbd->kbdqueue));
}

void dm2_v1_keybd_putkey(DM2_V1_Keybd *kbd, int16_t keycode)
{
    if (kbd->queuecnt >= DM2_V1_KBD_QUEUE_LENGTH)
        return;

    /* Translate Allegro key index via keytab */
    int16_t allegro_idx = keycode & 0x7F;
    int16_t scancode = dm2_v1_keytab[allegro_idx];
    if (scancode == 0)
        scancode = (int16_t)(keycode & 0x7F);

    /* Preserve modifier flags from upper bits */
    int16_t translated = scancode | (keycode & ~0x7F);

    kbd->kbdqueue[kbd->queueidx_in] = translated;
    kbd->queueidx_in = (int16_t)((kbd->queueidx_in + 1) % DM2_V1_KBD_QUEUE_LENGTH);
    kbd->queuecnt++;
}

int16_t dm2_v1_keybd_getkey(DM2_V1_Keybd *kbd)
{
    if (kbd->queuecnt <= 0)
        return -1;

    int16_t key = kbd->kbdqueue[kbd->queueidx_out];
    kbd->queueidx_out = (int16_t)((kbd->queueidx_out + 1) % DM2_V1_KBD_QUEUE_LENGTH);
    kbd->queuecnt--;
    return key;
}

bool dm2_v1_has_key(const DM2_V1_Keybd *kbd)
{
    return kbd->queuecnt != 0;
}

int16_t dm2_v1_getkey_translated(DM2_V1_Keybd *kbd)
{
    int16_t key = dm2_v1_keybd_getkey(kbd);
    if (key < 0)
        return -1;

    /* Cursor key translations from DM2_GETKEY_TRANSLATED */
    switch (key) {
    case 0x1048: return 0x4c;   /* up    -> numpad 8 */
    case 0x104b: return 0x4b;   /* left  -> numpad 4 */
    case 0x104d: return 0x4d;   /* right -> numpad 6 */
    case 0x1050: return 0x50;   /* down  -> numpad 2 */
    case 0x124b: return 0x4f;   /* shift+left  -> numpad 1 (end) */
    case 0x124d: return 0x51;   /* shift+right -> numpad 3 (pgdn) */
    default:     return key;
    }
}

int16_t dm2_v1_keybd_translate_ascii(int16_t scancode)
{
    int16_t idx = scancode & 0x7F;
    if (idx >= 128)
        return 0;

    if (scancode & 0x400) {
        /* Ctrl: use unshifted table, mask to control range */
        return (int16_t)(dm2_v1_DRVB_table1[idx] & 0x1F);
    }
    if (scancode & 0x200) {
        /* Shift */
        return (int16_t)dm2_v1_DRVB_table2[idx];
    }
    /* Unshifted */
    return (int16_t)dm2_v1_DRVB_table1[idx];
}
