/* --- Palette entry operations --- */

void dm2_v1_color_to_palettecolor(DM2_V1_Palette *pal, DM2_V1_EColor color) {
    pal->c.p = (uint8_t)color;
}

void dm2_v1_ui8_to_palettecolor(DM2_V1_Palette *pal, uint8_t val) {
    pal->c.p = val;
}

uint8_t dm2_v1_palettecolor_to_ui8(DM2_V1_Palette pal) {
    return pal.c.p;
}

DM2_V1_Pixel256 dm2_v1_palettecolor_to_pixel(DM2_V1_Palette pal) {
    return pal.c;
}

void dm2_v1_palette_conv(DM2_V1_Palette *pal, const DM2_V1_ColorConv *conv) {
    pal->c.p = conv[pal->c.p].p;
}

void dm2_v1_palette_data_init(DM2_V1_PaletteData *pd) {
    memset(pd, 0, sizeof(DM2_V1_PaletteData));
}

/* --- Driver operations --- */

DM2_V1_DriverSetColorsReceipt dm2_v1_driver_setcolors(
    const DM2_V1_GfxPalCallbacks *cb, void *ctx, const int8_t *dmpal)
{
    DM2_V1_DriverSetColorsReceipt receipt = {false, 0};
    if (!cb || !dmpal) return receipt;

    /* Convert 6-bit DAC palette to float colors and set via callback */
    float colors[256][3];
    for (int i = 0; i < 256; i++) {
        int base = i * 3;
        colors[i][0] = (float)((uint8_t)dmpal[base + 0]) * (float)DM2_V1_DMFCOL;
        colors[i][1] = (float)((uint8_t)dmpal[base + 1]) * (float)DM2_V1_DMFCOL;
        colors[i][2] = (float)((uint8_t)dmpal[base + 2]) * (float)DM2_V1_DMFCOL;
    }

    /* Fade in over 1000 steps */
    for (int step = 0; step < 1000; step++) {
        float t = (float)(step + 1) / 1000.0f;
        if (cb->wait_for_vsync) cb->wait_for_vsync(ctx);
        for (int i = 0; i < 256; i++) {
            if (cb->set_screen_color) {
                cb->set_screen_color(ctx, i,
                    colors[i][0] * t,
                    colors[i][1] * t,
                    colors[i][2] * t);
            }
        }
    }

    receipt.colors_set = true;
    receipt.colors_count = 256;
    return receipt;
}

DM2_V1_ConvertDriverPaletteReceipt dm2_v1_convert_driver_palette(
    const DM2_V1_GfxPalCallbacks *cb, void *ctx,
    const uint8_t *pb, int8_t *dmpal, bool immediate_colors)
{
    DM2_V1_ConvertDriverPaletteReceipt receipt = {false, 0};
    if (!pb || !dmpal) return receipt;

    /* Convert 8-bit ARGB palette: skip alpha byte, shift RGB >> 2 to 6-bit */
    for (int i = 0; i < 256; i++) {
        int src = i * 4; /* ARGB: alpha, R, G, B */
        int dst = i * 3;
        dmpal[dst + 0] = (int8_t)(pb[src + 1] >> 2);
        dmpal[dst + 1] = (int8_t)(pb[src + 2] >> 2);
        dmpal[dst + 2] = (int8_t)(pb[src + 3] >> 2);
    }

    if (immediate_colors && cb) {
        dm2_v1_driver_setcolors(cb, ctx, dmpal);
    }

    receipt.converted = true;
    receipt.entries_count = 256;
    return receipt;
}

DM2_V1_SelectPaletteSetReceipt dm2_v1_select_palette_set(
    const DM2_V1_GfxPalCallbacks *cb, void *ctx,
    int16_t set, const int8_t *dmpal, bool *immediate_colors_ptr)
{
    DM2_V1_SelectPaletteSetReceipt receipt = {false, 0};
    if (!cb) return receipt;

    if (set == 0) {
        /* Fade to black: backup current colors then fade down */
        float saved[256][3];
        for (int i = 0; i < 256; i++) {
            if (cb->get_screen_color) {
                cb->get_screen_color(ctx, i,
                    &saved[i][0], &saved[i][1], &saved[i][2]);
            } else {
                saved[i][0] = saved[i][1] = saved[i][2] = 0.0f;
            }
        }
        for (int step = 1000; step >= 0; step--) {
            float t = (float)step / 1000.0f;
            if (cb->wait_for_vsync) cb->wait_for_vsync(ctx);
            for (int i = 0; i < 256; i++) {
                if (cb->set_screen_color) {
                    cb->set_screen_color(ctx, i,
                        saved[i][0] * t,
                        saved[i][1] * t,
                        saved[i][2] * t);
                }
            }
        }
        if (immediate_colors_ptr) *immediate_colors_ptr = false;
    } else {
        /* Restore: call driver_setcolors */
        if (dmpal) {
            dm2_v1_driver_setcolors(cb, ctx, dmpal);
        }
        if (immediate_colors_ptr) *immediate_colors_ptr = true;
    }

    receipt.applied = true;
    receipt.mode = set;
    return receipt;
}

void dm2_v1_update_blit_palette(DM2_V1_PaletteData *pd, DM2_V1_Palette *pal) {
    if (pd) {
        pd->palette = pal;
    }
}

DM2_V1_XlatPaletteReceipt dm2_v1_xlat_palette(
    DM2_V1_Palette *pal, const DM2_V1_ColorConv *conv, int16_t *colors)
{
    DM2_V1_XlatPaletteReceipt receipt = {false, 0};
    if (!pal || !conv || !colors) return receipt;

    if (*colors > 0) {
        /* Translate each entry through the conversion table */
        for (int16_t i = 0; i < *colors; i++) {
            dm2_v1_palette_conv(&pal[i], conv);
        }
        receipt.final_colors = *colors;
    } else {
        /* Set colors to 256 and copy directly */
        *colors = 256;
        /* No conversion needed - just mark as full palette */
        receipt.final_colors = 256;
    }

    receipt.translated = true;
    return receipt;
}
