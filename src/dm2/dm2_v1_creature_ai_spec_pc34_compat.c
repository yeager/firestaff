const DM2_AIDefinition *dm2_v1_creature_ai_spec_from_type(
    uint8_t creature_type,
    DM2_QueryGdatCreatureWordFn query_gdat_word,
    void *ctx)
{
    if (!query_gdat_word) return NULL;
    uint16_t row = query_gdat_word(ctx, creature_type, 0x05);
    if (row >= DM2_AI_TABLE_SIZE) return NULL;
    return &s_ai_table[row];
}

const DM2_AIDefinition *dm2_v1_creature_ai_spec_by_row(int row)
{
    if (row < 0 || row >= DM2_AI_TABLE_SIZE) return NULL;
    return &s_ai_table[row];
}

int dm2_v1_creature_ai_is_static(const DM2_AIDefinition *ai)
{
    if (!ai) return 0;
    return (ai->flags & DM2_AI_FLAG_STATIC_OBJECT) != 0;
}
