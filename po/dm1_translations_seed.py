def main():
    """Apply complete translations to dm1.<lang>.po files in-place.

    Uses dm1_translations_complete.py (547 strings x 17 locales) if
    available, otherwise falls back to the 90-string seed in this file.
    Every msgid in dm1.<lang>.po gets a msgstr; missing translations
    fall through to the English source string.
    """
    import os
    try:
        from dm1_translations_complete import TRANSLATIONS as FULL
        print("Using dm1_translations_complete.py (547 x 17 locales)")
        table_dict = FULL
    except ImportError:
        print("Using dm1_translations_seed.py (90 strings x 17 locales)")
        table_dict = TRANSLATIONS
    po_dir = os.path.dirname(os.path.abspath(__file__))
    total_updated = 0
    for lang, table in table_dict.items():
        path = os.path.join(po_dir, f'dm1.{lang}.po')
        if not os.path.exists(path):
            print(f"SKIP {lang}: {path} not found")
            continue
        with open(path, 'r', encoding='utf-8') as f:
            text = f.read()
        # Process line by line: when we see a msgid line, find the
        # subsequent msgstr line and replace it.
        lines = text.split('\n')
        i = 0
        updated = 0
        while i < len(lines):
            line = lines[i]
            if line.startswith('msgid "'):
                # Extract msgid
                m = line[7:-1]  # strip 'msgid "' and trailing '"'
                if m == '':
                    i += 1
                    continue
                # Look ahead for the next msgstr line (skipping
                # continuation lines and any trailing comments).
                j = i + 1
                while j < len(lines):
                    next_line = lines[j]
                    if next_line.startswith('msgstr "'):
                        break
                    if next_line.startswith('#') or next_line.startswith('"') or next_line == '':
                        j += 1
                        continue
                    j += 1
                if j < len(lines) and lines[j].startswith('msgstr "'):
                    # Replace the existing msgstr in-place
                    if m in table:
                        translation = table[m]
                        escaped = translation.replace('\\', '\\\\').replace('"', '\\"')
                        lines[j] = f'msgstr "{escaped}"'
                        updated += 1
                    elif lines[j] == 'msgstr ""':
                        # No native translation; fall back to English
                        escaped = m.replace('\\', '\\\\').replace('"', '\\"')
                        lines[j] = f'msgstr "{escaped}"'
                i += 1
                continue
            i += 1
        new_text = '\n'.join(lines)
        with open(path, 'w', encoding='utf-8') as f:
            f.write(new_text)
        total_updated += updated
        print(f"  {lang}: updated {updated} msgids")
    print(f"Total translations applied: {total_updated}")


if __name__ == '__main__':
    main()
