#!/usr/bin/env python3
"""Unit-test the address-independent selection of title texture draws.

The tiny generated byte spans exercise verifier mechanics only. Retail claims
are checked separately against authenticated TITLE.BIN and Ymir captures.
"""

from __future__ import annotations

import unittest

from verify_nexus_title_sprite_screenshot import title_menu_draws


class TitleMenuDrawSelectionTests(unittest.TestCase):
    def test_selects_last_five_retail_bound_draws_in_order(self):
        textures = [bytes((index, index + 16, index + 32, index + 48))
                    for index in range(1, 7)]
        vram = bytearray(8 * 7)
        commands = []
        for index, texture in enumerate(textures):
            vram[index * 8:index * 8 + len(texture)] = texture
            # Each command is an unflipped 8x1 4bpp normal-sprite draw.
            words = (0, 0, 0x80, 0, index, 0x0101, 0, 0)
            commands.append((index * 32, words))

        selected = title_menu_draws(commands, bytes(vram), b"".join(textures))

        self.assertEqual([row[0] for row in selected], [1, 2, 3, 4, 5])
        self.assertEqual([row[3] for row in selected], [4, 8, 12, 16, 20])
        self.assertEqual([row[4] for row in selected], textures[1:])

    def test_rejects_incomplete_menu_draw_chain(self):
        textures = [bytes((index, index + 16, index + 32, index + 48))
                    for index in range(1, 5)]
        vram = bytearray(8 * 4)
        commands = []
        for index, texture in enumerate(textures):
            vram[index * 8:index * 8 + len(texture)] = texture
            commands.append((index * 32, (0, 0, 0x80, 0, index, 0x0101, 0, 0)))

        with self.assertRaisesRegex(ValueError, "fewer than five"):
            title_menu_draws(commands, bytes(vram), b"".join(textures))


if __name__ == "__main__":
    unittest.main()
